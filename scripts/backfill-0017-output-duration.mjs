import { readFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { readJson, withFileLock, writeJsonAtomic } from "../lib/atomic-json.mjs";
import { multisourceStatus } from "../lib/classic-multisource.mjs";
import { probeMultisourceDuration } from "../worker/classic-multisource-executor.mjs";
const root = process.argv[2];
const taskId = "86d5643d-d1cb-440b-93a3-ff0ffa4c31ca";
const outputId = "ce52498e-95f3-418c-b3eb-6a54be59855c";
const expected = "6021a271ad72426189a95c21c5cce3d410cb06688ce4f954cb57f5fb17fb6532";
const runtime = await readJson(path.join(root, "config/cutflow-runtime.json"), null);
const integration = await readJson(path.join(root, "data/classic-integration-runtime.json"), null);
const file = path.join(integration.nasRoot, "outbox", taskId, `${outputId}.mp4`);
const hash = async () => createHash("sha256").update(await readFile(file)).digest("hex");
if (await hash() !== expected) throw new Error("CANARY_OUTPUT_HASH_MISMATCH");
const durationSeconds = await probeMultisourceDuration(file, runtime.ffprobeExecutable);
await promisify(execFile)(runtime.ffmpegExecutable, ["-nostdin", "-v", "error", "-xerror", "-i", file, "-f", "null", "-"], { windowsHide: true });
const recordsFile = path.join(root, "data/classic-multisource-records.json");
await withFileLock(recordsFile, async () => {
  const records = await readJson(recordsFile, []);
  const record = records.find((item) => item.taskId === taskId);
  if (record?.status !== "review" || record.attempt !== 1) throw new Error("CANARY_RECORD_STATE_CHANGED");
  const output = record.outputs.find((item) => item.id === outputId && item.sha256 === expected && item.size === 6552951);
  if (!output) throw new Error("CANARY_OUTPUT_BINDING_CHANGED");
  output.durationSeconds = durationSeconds;
  await writeJsonAtomic(recordsFile, records);
  await writeJsonAtomic(path.join(integration.nasRoot, "outbox", taskId, "status.json"), await multisourceStatus(root, taskId));
});
if (await hash() !== expected) throw new Error("CANARY_OUTPUT_CHANGED_DURING_METADATA_FIX");
console.log(JSON.stringify({ taskId, outputId, durationSeconds, sha256: expected, fullDecode: "pass", taskRetried: false, mediaModified: false }));

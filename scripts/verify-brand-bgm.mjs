import {readFile,mkdir,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {prepareBrandAudio,selectBrandBgm,BGM_ROOT} from '../worker/brand-bgm.mjs';
import {loadRenderRuntimeConfig} from '../worker/runtime-config.mjs';
const exec=promisify(execFile),root=process.cwd(),runtime=await loadRenderRuntimeConfig(root);
const out=path.join(root,'artifacts/brand-bgm-20261021');await mkdir(out,{recursive:true});
const json=async f=>JSON.parse(await readFile(f,'utf8'));
const prior=path.join(root,'.project-governance/evidence/brand-copy-20261020');
const protectedFiles=['data/production-path.json','config/cutflow-runtime.json','worker/scheduler-v2-policy.mjs','worker/render-overlays.py','worker/brand-copy-render.mjs'];
const hash=async f=>createHash('sha256').update(await readFile(path.join(root,f))).digest('hex');
const before=await Promise.all(protectedFiles.map(hash));
const run=(exe,args)=>exec(exe,args,{windowsHide:true,timeout:60000,maxBuffer:4*1024*1024});
const report={providerCalls:0,sourceVideoGeneration:0,productionEnabled:false,subjectiveListening:'pending',outputs:[],checks:{}};
for(const [brand,caseId,productId] of [['GC','copy-gc-multi-output','P001'],['TT','copy-tt-ootd','TT4-M1'],['NW','copy-gc-multi-output','P001'],['UNKNOWN','copy-gc-multi-output','P001']]){
  const edl=await json(path.join(prior,caseId,'edit/render-plan-edl.json'));
  const product=edl.products.find(p=>p.product_id===productId),duration=product.duration_seconds;
  const directory=path.join(out,brand);await mkdir(directory,{recursive:true});
  const batch={brandCopyContext:{brandId:brand,provenance:'isolated_canary'}};
  const audio=await prepareBrandAudio({root,batch,product,duration,directory,ffmpeg:runtime.ffmpegExecutable,ffprobe:runtime.ffprobeExecutable});
  if(brand==='NW')assert.ok(['selected','cached'].includes(audio.decision.status),JSON.stringify(audio.decision));
  else assert.equal(audio.decision.status,'no_bgm');
  const source=path.join(root,'artifacts/brand-copy-20261020',`${caseId}-${productId}.mp4`),target=path.join(out,`${brand}.mp4`);
  await run(runtime.ffmpegExecutable,['-v','error','-y','-i',source,'-i',audio.path,'-map','0:v:0','-map','1:a:0','-c:v','copy','-c:a','aac','-b:a','192k','-t',String(duration),'-movflags','+faststart',target]);
  await run(runtime.ffmpegExecutable,['-v','error','-i',target,'-f','null','-']);
  const videoHash=async f=>(await run(runtime.ffmpegExecutable,['-v','error','-i',f,'-map','0:v:0','-c','copy','-f','hash','-hash','sha256','-'])).stdout.trim();
  assert.equal(await videoHash(source),await videoHash(target));
  report.outputs.push({brand,file:target,duration,decision:audio.decision,decode:'pass',videoAndHookUnchanged:true,limitation:brand==='NW'?'GC visual reused solely for NW audio integration, not an NW product delivery':undefined});
  console.log(brand,audio.decision.status,audio.decision.bgmFile);
}
const nw=await selectBrandBgm({root,brand:'NW',ffmpeg:runtime.ffmpegExecutable});
assert.notEqual(nw.bgmFile,report.outputs.find(o=>o.brand==='NW').decision.bgmFile);report.checks.nwRecentAvoidance=true;
const fake=path.join(out,`nas-unavailable-${Date.now()}`);await mkdir(fake,{recursive:true});
const cacheRoot=path.join(out,'fallback-cache'),mapping={GC:'基督'};
await mkdir(path.join(fake,'基督'),{recursive:true});
// Same root is made unavailable after its known-good track has been cached.
const {copyFile,rename}=await import('node:fs/promises');
await copyFile(report.outputs.find(o=>o.brand==='NW').decision.path,path.join(fake,'基督','one.wav'));
const first=await selectBrandBgm({root,brand:'GC',ffmpeg:runtime.ffmpegExecutable,directory:fake,mapping,cacheRoot});assert.equal(first.status,'selected');
const single=await selectBrandBgm({root,brand:'GC',ffmpeg:runtime.ffmpegExecutable,directory:fake,mapping,cacheRoot});assert.equal(single.bgmFile,first.bgmFile);
await rename(path.join(fake,'基督'),path.join(fake,'offline'));
const cached=await selectBrandBgm({root,brand:'GC',ffmpeg:runtime.ffmpegExecutable,directory:fake,mapping,cacheRoot});assert.equal(cached.status,'cached');
await mkdir(path.join(fake,'基督'));await writeFile(path.join(fake,'基督','broken.mp3'),'invalid audio');
const corrupt=await selectBrandBgm({root,brand:'GC',ffmpeg:runtime.ffmpegExecutable,directory:fake,mapping,cacheRoot});assert.equal(corrupt.status,'cached');
report.checks.singleTrackRepeat=true;report.checks.nasOfflineSameBrandCache=true;report.checks.corruptTrackSameBrandCache=true;
assert.deepEqual(await Promise.all(protectedFiles.map(hash)),before);report.checks.protectedFilesUnchanged=true;
report.nasRoot=BGM_ROOT;report.mapping=await json(path.join(root,'config/brand-bgm-directories.json'));
await writeFile(path.join(out,'report.json'),JSON.stringify(report,null,2));
console.log('REPORT',path.join(out,'report.json'));
